"""
Console table formatting for two-locus frequency states.
This file is generated by GPT 6 Astra.
"""
from __future__ import annotations

from evolution import state


def print_frequency_table(
    current_state: state.MWUAFrequencyState | state.GeneralFrequencyState,
    loci: list[state.Locus],
    title: str,
) -> None:
    """Print joint frequencies and allele marginals for loci A and B.

    Supports either state representation; rounds only the displayed values.
    """
    row_alleles, column_alleles = loci
    headers = ["A / B", *(allele.id for allele in column_alleles), "A frequency"]
    rows = [
        [
            a.id,
            *(f"{current_state.get_genotype_frequency((a, b)):.4f}"
              for b in column_alleles),
            f"{current_state.get_allele_frequency(a):.4f}",
        ]
        for a in row_alleles
    ]
    total = sum(
        current_state.get_genotype_frequency((a, b))
        for a in row_alleles for b in column_alleles
    )
    rows.append([
        "B frequency",
        *(f"{current_state.get_allele_frequency(b):.4f}" for b in column_alleles),
        f"{total:.4f}",
    ])
    widths = [max(len(cell) for cell in column) for column in zip(headers, *rows)]

    def border(left, middle, right):
        return left + middle.join("─" * (width + 2) for width in widths) + right

    def format_row(cells):
        return "│ " + " │ ".join(
            cell.ljust(width) if index == 0 else cell.rjust(width)
            for index, (cell, width) in enumerate(zip(cells, widths))
        ) + " │"

    print(f"\n{title}")
    print(border("┌", "┬", "┐"))
    print(format_row(headers))
    print(border("├", "┼", "┤"))
    for row in rows[:-1]:
        print(format_row(row))
    print(border("├", "┼", "┤"))
    print(format_row(rows[-1]))
    print(border("└", "┴", "┘"))

